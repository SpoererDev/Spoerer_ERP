const normalize = (value) => String(value || '')
  .normalize('NFD')
  .replace(/[̀-ͯ]/g, '')
  .toLowerCase()
  .replace(/[^a-z0-9]/g, '');

/** Busca la comuna por nombre ignorando tildes, mayúsculas y espacios. */
export const findComunaByName = (name) => {
  const target = normalize(name);
  if (!target) return null;
  return COMUNAS_CHILE.find(c => normalize(c.name) === target) || null;
};
